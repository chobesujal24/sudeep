## Understanding Lumens vs. Wattage
Historically, buyers looked at wattage to determine brightness. With LEDs, you must look at **Lumens**. A high-quality LED street light will produce significantly more lumens per watt (luminous efficacy) than cheaper alternatives. Always measure the total lumen output required for your road width and mounting height.

## IP66 and Weather Resistance
Street lights face monsoon rains, blistering sun, and heavy dust. Ensure any fixture you purchase has at least an **IP65 or IP66 rating**, meaning it is completely dust-tight and protected against powerful water jets. The housing should be made of corrosion-resistant die-cast aluminum.

## Surge Protection in India
Power grids can be unpredictable. High-quality LED street lights must feature built-in **Surge Protection Devices (SPD)** of at least 10kV to protect the sensitive LED drivers from lightning strikes and voltage spikes.

